import 'package:firebase_core/firebase_core.dart';
import 'package:flutter/material.dart';

import 'firebase_options.dart'; // generated by "flutterfire configure"
import 'navigation/bottom_navigation.dart';

Future<void> main() async {
  // Needed before using Firebase (or any plugin) before runApp().
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  runApp(const CampusConnectApp());
}

class CampusConnectApp extends StatelessWidget {
  const CampusConnectApp({super.key});

  @override
  Widget build(BuildContext context) {
    return MaterialApp(
      title: 'CampusConnect',
      debugShowCheckedModeBanner: false,
      theme: ThemeData(
        useMaterial3: true,
        colorScheme: ColorScheme.fromSeed(seedColor: const Color(0xFF3F51B5)),
        scaffoldBackgroundColor: const Color(0xFFF5F6FA),
        appBarTheme: const AppBarTheme(
          centerTitle: true,
          backgroundColor: Color(0xFF3F51B5),
          foregroundColor: Colors.white,
        ),
      ),
      // initialIndex: 3 opens the Services tab so you can test your module.
      // In the final merged app, teammates use the default (0 = Home) and
      // pass their real screens: MainNavigation(homeScreen: HomeScreen(), ...)
      home: const MainNavigation(initialIndex: 3),
    );
  }
}
